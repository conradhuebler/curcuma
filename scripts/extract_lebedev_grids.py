import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
XTB = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "external", "xtb")
SRC = os.path.join(XTB, "src", "solv", "lebedev.f90")
OUT = os.path.join(ROOT, "src", "core", "solvation", "lebedev_xtb_grids.h")

NUM = r"([-+]?\d*\.\d+(?:[eEdD][-+]?\d+)?)_wp"
SUB_RE = re.compile(r"pure subroutine ld(\d{4})\(x, w, n\)(.*?)end subroutine ld\d{4}", re.S)
ASSIGN_RE = re.compile(r"^\s*([abv])\s*=\s*" + NUM + r"\s*$", re.M)
CALL_RE = re.compile(r"call genOh(\d)\(")


def parse():
    text = open(SRC).read()
    grids = []
    for m in SUB_RE.finditer(text):
        size = int(m.group(1))
        body = m.group(2)
        cur = {"a": 0.0, "b": 0.0, "v": 0.0}
        calls = []
        for line in body.splitlines():
            am = ASSIGN_RE.match(line)
            if am:
                cur[am.group(1)] = am.group(2).replace("d", "e").replace("D", "e")
                continue
            cm = CALL_RE.search(line)
            if cm:
                gen = int(cm.group(1))
                calls.append((gen, cur["a"] if gen >= 4 else "0.0", cur["b"] if gen == 6 else "0.0", cur["v"]))
        npts = sum({1: 6, 2: 12, 3: 8, 4: 24, 5: 24, 6: 48}[c[0]] for c in calls)
        if npts != size:
            sys.exit(f"ld{size:04d}: generator calls give {npts} points")
        grids.append((size, calls))
    return grids


