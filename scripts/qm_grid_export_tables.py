#!/usr/bin/env python3
"""Export the DFT quadrature tables of PySCF into a C++ header (WP4, native KS-DFT grid).

Writes src/core/energy_calculators/qm_methods/qm_grid_tables.hpp with
  * the Lebedev-Laikov orbit generators (code, a, b, v) of every order PySCF ships (6 ... 5810 points),
    recorded by intercepting pyscf.dft.LebedevGrid.SphGenOh while MakeAngularGrid(n) runs. curcuma's
    sphGenOh (qm_grid.cpp) expands them with the same octahedral rules in the same point order, so the
    angular grids equal PySCF's point by point;
  * the Bragg-Slater radii (pyscf.data.radii.BRAGG, Bohr) used by the Becke size adjustment;
  * the Treutler-Ahlrichs xi factors (pyscf.dft.radi._treutler_ahlrichs_xi).
Values are printed with repr() (shortest exact round trip), so the header holds PySCF's doubles bit for bit.

Run with the reference venv (system python has no PySCF):
    ~/.venvs/qmref/bin/python scripts/qm_grid_export_tables.py

Sources of the numbers: V. I. Lebedev, D. N. Laikov, Dokl. Math. 59, 477 (1999) via the Laikov / van Wuellen /
Knizia code in PySCF; J. C. Slater, J. Chem. Phys. 41, 3199 (1964) (Bragg-Slater radii); O. Treutler,
R. Ahlrichs, J. Chem. Phys. 102, 346 (1995) (xi).
Claude Generated (Oct 2026).
"""
import os
import sys

import pyscf
from pyscf.data import radii
from pyscf.dft import LebedevGrid as L
from pyscf.dft import radi

ZMAX = 86  # Rn; the native basis covers H-Ne, the tables go further at no cost

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "core", "energy_calculators", "qm_methods", "qm_grid_tables.hpp")


def record_orders():
    calls = []
    orig = L.SphGenOh

    def spy(code, a, b, v):
        calls.append((int(code), float(a), float(b), float(v)))
        return orig(code, a, b, v)

    L.SphGenOh = spy
    orders = []
    try:
        for npts in sorted(int(n) for n in L.LEBEDEV_NGRID if n > 1):
            calls.clear()
            g = L.MakeAngularGrid(npts)
            assert g.shape[0] == npts, (npts, g.shape)
            degree = [k for k, v in L.LEBEDEV_ORDER.items() if v == npts][0]
            orders.append((npts, degree, list(calls)))
    finally:
        L.SphGenOh = orig
    return orders


def main():
    orders = record_orders()
    lines = []
    w = lines.append
    w("/*")
    w(" * <Native QM: DFT quadrature tables (Lebedev-Laikov generators, Bragg radii, Treutler xi)>")
    w(" * Copyright (C) 2026 Conrad Hübler <Conrad.Huebler@gmx.net>")
    w(" *")
    w(" * GENERATED by scripts/qm_grid_export_tables.py from PySCF {} -- do not edit by hand.".format(pyscf.__version__))
    w(" * Lebedev orbits: V. I. Lebedev, D. N. Laikov, Dokl. Math. 59, 477 (1999) (Laikov/van Wuellen/Knizia")
    w(" * code as shipped in pyscf/dft/LebedevGrid.py). Weights are normalised to sum 1 (multiply by 4 pi).")
    w(" * Bragg radii (Bohr): pyscf.data.radii.BRAGG; Treutler xi: O. Treutler, R. Ahlrichs, JCP 102, 346 (1995).")
    w(" * Claude Generated (Oct 2026, WP4).")
    w(" *")
    w(" * This program is free software under GPL-3.0")
    w(" */")
    w("")
    w("#pragma once")
    w("")
    w("namespace qmgrid {")
    w("namespace tables {")
    w("")
    w("/// One octahedral orbit: code as pyscf SphGenOh (0: 6 pts, 1: 12, 2: 8, 3: 24 (a,a,b), 4: 24 (a,b,0), 5: 48 (a,b,c)).")
    w("struct LebedevOrbit {")
    w("    int code;")
    w("    double a, b, v;")
    w("};")
    w("")
    w("/// Orbits of one Lebedev grid: npts points, exact for spherical harmonics up to degree `degree`.")
    w("struct LebedevGridDef {")
    w("    int npts;")
    w("    int degree;")
    w("    int first;  ///< index into kLebedevOrbits")
    w("    int count;")
    w("};")
    w("")
    w("// clang-format off")
    w("inline constexpr LebedevOrbit kLebedevOrbits[] = {")
    defs = []
    idx = 0
    for npts, degree, calls in orders:
        w("    // {} points, degree {}".format(npts, degree))
        for code, a, b, v in calls:
            w("    {{{}, {}, {}, {}}},".format(code, repr(a), repr(b), repr(v)))
        defs.append((npts, degree, idx, len(calls)))
        idx += len(calls)
    w("};")
    w("")
    w("inline constexpr LebedevGridDef kLebedevGrids[] = {")
    for npts, degree, first, count in defs:
        w("    {{{}, {}, {}, {}}},".format(npts, degree, first, count))
    w("};")
    w("inline constexpr int kNumLebedevGrids = {};".format(len(defs)))
    w("")
    w("/// Bragg-Slater radii in Bohr, index = Z (0 = ghost), Z <= {}.".format(ZMAX))
    w("inline constexpr double kBraggRadiiBohr[] = {")
    for z in range(ZMAX + 1):
        w("    {},".format(repr(float(radii.BRAGG[z]))))
    w("};")
    w("")
    w("/// Treutler-Ahlrichs xi scale factors, index = Z (0 = ghost), Z <= {}.".format(ZMAX))
    w("inline constexpr double kTreutlerXi[] = {")
    for z in range(ZMAX + 1):
        w("    {},".format(repr(float(radi._treutler_ahlrichs_xi[z]))))
    w("};")
    w("inline constexpr int kMaxTableZ = {};".format(ZMAX))
    w("// clang-format on")
    w("")
    w("}  // namespace tables")
    w("}  // namespace qmgrid")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote {} ({} grids, {} orbits)".format(os.path.normpath(OUT), len(defs), idx))


if __name__ == "__main__":
    sys.exit(main())
