#!/usr/bin/env python3
"""List class member functions declared in src/**/*.h that no code refers to.

Rule (name based, no type information): a member `Class::name` declared on one line in a header
is a candidate. It is classified by how often the bare word `name` occurs in C++ sources
(src, test_cases; .h .hpp .cpp .cu .hip), not counting comment lines and `Class::name(` definitions:

  dead           no other occurrence anywhere, not even inside its own header
  same-file      occurs again only inside its own header
  alive-by-name  occurs in other files (may be another class's member of the same name; needs the compiler)
  lib            lives in a unit/math/GPU header that is deleted only on purpose

Usage: scripts/find_dead_members.py [--md OUT.md]   (run from the repository root)
A hit is not a proof: names built by macros or token pasting and calls from outside the repository
are invisible. Delete in a branch and let the compiler decide; build the optional backends too.
"""
import collections
import glob
import re
import sys

LIB = ('units.h', 'GTOIntegrals', 'LofthusOverlap', 'xtb_multipole_ints', 'lebedev', 'portable_',
       'cuda/', 'rocm/', 'vulkan', 'gpu', 'blas_threads')
CODE = ('.h', '.hpp', '.cpp', '.cu', '.hip')

files = [f for f in glob.glob('**/*', recursive=True)
         if f.endswith(CODE) and f.startswith(('src/', 'test_cases/')) and '/external/' not in f]
lines = {f: open(f, errors='replace').read().split('\n') for f in files}

DECL = re.compile(r'^(\s+)(?:\[\[nodiscard\]\]\s*)?(?:(?:static|inline|constexpr|const|explicit)\s+)*'
                  r'(?!return\b|delete\b|new\b|else\b|throw\b|case\b|using\b|typedef\b)'
                  r'([A-Za-z_][\w:<>,&\*\s]*?[\s&\*>])(\w+)\s*\(([^;{]*)\)\s*(const)?\s*(noexcept)?\s*(;|\{.*)?$')
classes = set()
for L in lines.values():
    for l in L:
        m = re.match(r'^\s*(?:class|struct)\s+(\w+)', l)
        if m:
            classes.add(m.group(1))


def enclosing(L, i):
    ind = len(L[i]) - len(L[i].lstrip())
    for k in range(i - 1, -1, -1):
        l = L[k]
        if re.match(r'^\s*(public|private|protected)\s*:', l) or re.match(r'^\s*(public|private|protected)\s+slots\s*:', l):
            continue
        if l.strip() and len(l) - len(l.lstrip()) < ind:
            m = re.match(r'^\s*(?:template.*)?(?:class|struct)\s+(\w+)', l)
            if m:
                return m.group(1)
            if re.match(r'^\s*(namespace|enum|extern)', l):
                return None
            ind = len(l) - len(l.lstrip())
    return None


def is_comment(l):
    return l.strip().startswith(('//', '*', '/*'))


cands = {}
for f, L in lines.items():
    if not (f.startswith('src/') and f.endswith(('.h', '.hpp'))):
        continue
    for i, l in enumerate(L):
        if is_comment(l) or l.lstrip().startswith('#') or re.search(r'\b(virtual|override|final)\b', l):
            continue
        m = DECL.match(l)
        if not m:
            continue
        name = m.group(3)
        cls = enclosing(L, i)
        if cls and len(name) > 3 and not name.startswith(('operator', '~')) and name not in classes:
            cands.setdefault((f, cls, name), i)

occ = collections.defaultdict(list)
word = re.compile(r'[A-Za-z_]\w*')
for f, L in lines.items():
    for i, l in enumerate(L):
        if is_comment(l):
            continue
        for w in set(word.findall(l.split('//')[0])):
            occ[w].append((f, i))

rows = []
for (f, cls, name), di in cands.items():
    other = same = 0
    for g, i in occ[name]:
        line = lines[g][i]
        if re.search(r'\b\w+::' + re.escape(name) + r'\s*\(', line):
            continue
        if g == f:
            if i != di:
                same += 1
        else:
            other += 1
    cat = 'lib' if any(k in f for k in LIB) else 'alive-by-name' if other else 'same-file' if same else 'dead'
    rows.append((cat, f, cls, name, other, same))

c = collections.Counter(r[0] for r in rows)
print(dict(c))
if '--md' in sys.argv:
    out = sys.argv[sys.argv.index('--md') + 1]
    with open(out, 'w') as fh:
        fh.write('# Member functions without callers\n\n')
        fh.write('Generated by `scripts/find_dead_members.py` (rule and limits in its docstring). Candidates, not proofs.\n\n')
        n_alive = sum(1 for r in rows if r[0] == 'alive-by-name')
        fh.write(f'Not listed: {n_alive} members whose name occurs in other files (real callers, or a same-named member of another class; only the compiler tells).\n\n')
        for cat, title in (('dead', 'No other occurrence in src/ or test_cases/ (can go)'),
                           ('same-file', 'Occur again only inside their own header'),
                           ('lib', 'Unit, math and GPU headers (kept on purpose, decide per header)')):
            sel = [r for r in rows if r[0] == cat]
            fh.write(f'## {title}: {len(sel)}\n\n')
            by = collections.defaultdict(list)
            for r in sel:
                by[r[1]].append(f'{r[2]}::{r[3]}')
            for f in sorted(by):
                fh.write(f'- `{f}`: ' + ', '.join(sorted(by[f])) + '\n')
            fh.write('\n')
